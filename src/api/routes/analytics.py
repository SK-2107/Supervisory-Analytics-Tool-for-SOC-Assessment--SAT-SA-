@router.get("/evidence/{finding_id}")
def trace_finding_evidence(finding_id: str):
    """
    Traces a structured finding to its source evidence database records (Alerts, Tickets, Notes, Shifts, Assets).
    """
    conn = get_db_connection(read_only=True)
    try:
        df_finding = conn.execute("SELECT * FROM findings WHERE finding_id = ?", [finding_id]).df()
        if df_finding.empty:
            raise HTTPException(status_code=404, detail=f"Finding with ID '{finding_id}' not found.")

        finding_row = df_finding.iloc[0].to_dict()
        source_type = finding_row["source_record_type"]
        evidence_ids = [e.strip() for e in finding_row["evidence_record_ids"].split(",") if e.strip()]

        records = []
        if evidence_ids:
            placeholders = ",".join(["?"] * len(evidence_ids))
            if source_type == "alert":
                records = conn.execute(f"SELECT * FROM alerts WHERE alert_id IN ({placeholders})", evidence_ids).df().to_dict(orient="records")
            elif source_type == "ticket":
                records = conn.execute(f"SELECT * FROM tickets WHERE ticket_id IN ({placeholders})", evidence_ids).df().to_dict(orient="records")
            elif source_type == "note":
                records = conn.execute(f"SELECT * FROM investigation_notes WHERE note_id IN ({placeholders})", evidence_ids).df().to_dict(orient="records")
            elif source_type == "shift":
                records = conn.execute(f"SELECT * FROM shift_logs WHERE log_id IN ({placeholders})", evidence_ids).df().to_dict(orient="records")

        return {
            "status": "success",
            "finding": finding_row,
            "evidence_records_count": len(records),
            "evidence_records": records
        }
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(
            status_code=500,
            detail={"error": "Failed to trace finding evidence", "message": str(e)}
        )
    finally:
        conn.close()


