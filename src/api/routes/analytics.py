@router.get("/overview")
def get_soc_overview():
    """
    Returns high-level SOC operational KPIs and CSE assessment metrics.
    """
    conn = get_db_connection(read_only=True)
    try:
        df_stats = conn.execute("""
            SELECT 
                (SELECT COUNT(*) FROM cses) AS total_cses,
                (SELECT COUNT(*) FROM assets) AS total_assets,
                (SELECT COUNT(*) FROM alerts) AS total_alerts,
                (SELECT COUNT(*) FROM tickets) AS total_tickets,
                (SELECT COUNT(*) FROM findings) AS total_findings,
                (SELECT COUNT(*) FROM supervisory_scores WHERE entity_type='cse' AND total_score >= 35) AS high_attention_cses
        """).df()

        if df_stats.empty:
            return {"status": "success", "kpis": {}}

        row = df_stats.iloc[0].to_dict()
        row["disclaimer"] = "Prototype Supervisory Attention Indicator — not an official NCIIPC risk score."
        return {
            "status": "success",
            "kpis": row
        }
    except Exception as e:
        raise HTTPException(
            status_code=500,
            detail={"error": "Failed to retrieve SOC overview KPIs", "message": str(e)}
        )
    finally:
        conn.close()


